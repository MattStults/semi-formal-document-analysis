"""make_arm.py must refuse every way of producing a diff it cannot describe."""

import json
import os
import sys

import pytest

HERE = os.path.dirname(os.path.abspath(__file__))
if HERE not in sys.path:
    sys.path.insert(0, HERE)

import make_arm as M  # noqa: E402

SRC = "alpha\nTARGET LINE\nbeta\ngamma\n"
LINE = "TARGET LINE"


def test_deletes_the_named_line_and_nothing_else():
    out, idx = M.delete_line(SRC, LINE)
    assert out == "alpha\nbeta\ngamma\n"
    assert idx == 1


def test_a_line_that_is_absent_REFUSES_rather_than_producing_equal_arms():
    # The failure this exists for: the source was edited, the line is gone, and
    # a silent no-op would run an A/B where both arms are the same prompt.
    with pytest.raises(M.ArmError, match="byte-identical"):
        M.delete_line(SRC, "a line nobody wrote")


def test_a_line_appearing_twice_REFUSES():
    doubled = SRC + LINE + "\n"
    with pytest.raises(M.ArmError, match="occurs 2 times"):
        M.delete_line(doubled, LINE)


def test_an_empty_line_REFUSES():
    with pytest.raises(M.ArmError, match="no-op"):
        M.delete_line(SRC, "   ")


def test_matching_ignores_surrounding_whitespace_on_both_sides():
    out, _ = M.delete_line("alpha\n  TARGET LINE  \nbeta\n", LINE + " ")
    assert "TARGET" not in out


def test_verify_catches_a_variant_that_changed_another_line():
    tampered = "alpha\nbeta CHANGED\ngamma\n"
    with pytest.raises(M.ArmError, match="other than the target"):
        M.verify(SRC, tampered, LINE)


def test_verify_catches_a_variant_that_still_holds_the_line():
    with pytest.raises(M.ArmError, match="still present"):
        M.verify(SRC, SRC, LINE)


def test_the_written_arm_carries_NO_provenance_header(tmp_path):
    # ⛔ The regression this pins: a "generated by ..." comment in the file is
    # one more line of SYSTEM PROMPT than the other arm has, so the measured
    # difference would be two lines wide while the report says one.
    src = tmp_path / "src.md"
    src.write_text(SRC, encoding="utf-8")
    out = tmp_path / "arm.md"
    M.build(str(src), LINE, str(out))
    written = out.read_text(encoding="utf-8")
    assert written == "alpha\nbeta\ngamma\n"
    assert "make_arm" not in written and "GENERATED" not in written
    assert len(written.split("\n")) == len(SRC.split("\n")) - 1


def test_provenance_lands_in_a_sidecar_with_the_source_sha(tmp_path):
    src = tmp_path / "src.md"
    src.write_text(SRC, encoding="utf-8")
    out = tmp_path / "arm.md"
    M.build(str(src), LINE, str(out))
    prov = json.loads((tmp_path / "arm.md.provenance.json").read_text())
    assert prov["deleted_line"] == LINE
    assert prov["deleted_line_number"] == 2
    assert len(prov["source_sha256"]) == 64


def test_build_REFUSES_before_writing_anything_when_the_line_is_absent(tmp_path):
    src = tmp_path / "src.md"
    src.write_text(SRC, encoding="utf-8")
    out = tmp_path / "arm.md"
    with pytest.raises(M.ArmError):
        M.build(str(src), "not here", str(out))
    assert not out.exists(), "a refused build must leave no half-made arm"


def test_the_real_target_line_is_present_exactly_once_in_the_live_prompt():
    # If this fails, the eval below it is measuring something else.
    path = os.path.join(HERE, "..", "prompt", "00_task.md")
    text = open(path, encoding="utf-8").read()
    want = ('This is the most important rule here, and it is **not** '
            '"only write what the text says".')
    assert [ln.strip() for ln in text.split("\n")].count(want) == 1
