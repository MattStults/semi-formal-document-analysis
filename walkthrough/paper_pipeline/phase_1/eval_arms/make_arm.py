#!/usr/bin/env python3
"""Generate an eval arm as a VERIFIED one-line diff of a live prompt file.

An A/B arm that is a hand-made copy of a prompt file is a lie waiting to
happen: the original gets edited, the copy does not, and the run then measures
every drift between them while reporting the name of the one line you meant to
test. Three of this project's worst hours went to exactly that shape — a prompt
edited after it was read, with nothing checking.

⇒ The variant is GENERATED from the current source every time, and the
generator refuses unless the deletion is exactly what it claims:

    - the line must appear EXACTLY once  (0 => already gone or retyped;
                                          2 => the diff is not one line)
    - the output must differ from the source by that line and nothing else

⛔ IT DELETES WHOLE LINES ONLY. A within-line edit would make "one line
changed" true by character count and false by meaning, and the report says
one line.

    python3 make_arm.py --source ../prompt/00_task.md \\
                        --delete-line "This is the most ..." \\
                        --out 00_task_no_emphasis.md
"""

import argparse
import hashlib
import json
import os
import sys

HERE = os.path.dirname(os.path.abspath(__file__))


class ArmError(RuntimeError):
    """The diff is not the diff that was claimed."""


def delete_line(source_text, line):
    """Return (variant_text, index). Raises unless `line` occurs exactly once.

    Matching is on the STRIPPED line, so trailing whitespace in either the
    file or the argument cannot silently produce a zero-match "success".
    """
    want = line.strip()
    if not want:
        raise ArmError("refusing to delete an empty line: that is a no-op "
                       "that would report as a successful one-line diff")
    lines = source_text.split("\n")
    hits = [i for i, ln in enumerate(lines) if ln.strip() == want]
    if not hits:
        raise ArmError(
            f"line not found in source, so nothing would be deleted and the "
            f"two arms would be byte-identical: {want!r}")
    if len(hits) > 1:
        raise ArmError(
            f"line occurs {len(hits)} times at lines "
            f"{[i + 1 for i in hits]}; deleting all of them is not the "
            f"one-line change this claims to measure: {want!r}")
    i = hits[0]
    return "\n".join(lines[:i] + lines[i + 1:]), i


def verify(source_text, variant_text, line):
    """The output differs from the input by that line and nothing else."""
    want = line.strip()
    src = [ln for ln in source_text.split("\n")]
    var = [ln for ln in variant_text.split("\n")]
    # Order matters: "still present" is the specific diagnosis and the line
    # count is the catch-all, so the specific one is tested first or it can
    # never be reported.
    if any(ln.strip() == want for ln in var):
        raise ArmError("the line is still present in the variant")
    if len(var) != len(src) - 1:
        raise ArmError(f"variant is {len(var)} lines, source is {len(src)}; "
                       f"expected exactly one fewer")
    removed = [ln for ln in src if ln.strip() == want]
    if [ln for ln in src if ln.strip() != want] != \
       [ln for ln in var if ln.strip() != want]:
        raise ArmError("lines other than the target differ between the arms")
    return removed[0]


def build(source_path, line, out_path):
    with open(source_path, encoding="utf-8") as fh:
        source = fh.read()
    variant, idx = delete_line(source, line)
    verify(source, variant, line)
    # ⛔ NO PROVENANCE HEADER IN THE FILE. This file is concatenated into the
    # system block verbatim, so a "generated by ..." comment is one more line
    # of prompt the other arm does not have — the diff would be two lines wide
    # while the report says one. Provenance goes in a sidecar the model never
    # sees.
    with open(out_path, "w", encoding="utf-8") as fh:
        fh.write(variant)
    with open(out_path + ".provenance.json", "w", encoding="utf-8") as fh:
        json.dump({
            "generated_by": "eval_arms/make_arm.py",
            "source": os.path.relpath(source_path, HERE),
            "source_sha256": hashlib.sha256(source.encode()).hexdigest(),
            "deleted_line_number": idx + 1,
            "deleted_line": line.strip(),
            "note": "Regenerate after any edit to the source; the sha above is "
                    "what this arm was built from.",
        }, fh, indent=1)
    return idx + 1


def main(argv=None):
    p = argparse.ArgumentParser(description=__doc__)
    p.add_argument("--source", required=True)
    p.add_argument("--delete-line", required=True)
    p.add_argument("--out", required=True)
    a = p.parse_args(argv)
    src = a.source if os.path.isabs(a.source) else os.path.join(HERE, a.source)
    out = a.out if os.path.isabs(a.out) else os.path.join(HERE, a.out)
    try:
        n = build(src, a.delete_line, out)
    except ArmError as exc:
        print(f"⛔ {exc}", file=sys.stderr)
        return 2
    print(f"✓ {os.path.relpath(out, HERE)} — {os.path.basename(src)} "
          f"minus line {n}")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
