"""Back-fill paragraph-level provenance (locator/4 facts) onto rules.lp.

For each norm in rules.lp with a source/2 fact, we hold a PROBE: a verbatim
fragment of the constitution sentence the rule was encoded from (taken from
the rule's own comment in rules.lp). We look for clauses in
constitution_clauses.json whose `quote` contains that probe as an EXACT
substring. A norm gets a locator only if EXACTLY ONE clause matches.

Usage:
  .venv/bin/python backfill_locators.py            # report only
  .venv/bin/python backfill_locators.py --write    # rewrite rules.lp
"""
from __future__ import annotations

import json
import os
import re
import sys

HERE = os.path.dirname(os.path.abspath(__file__))
CLAUSES = os.path.join(HERE, "constitution_clauses.json")
RULES = os.path.join(HERE, "rules.lp")

# norm id -> verbatim probe (must appear inside the matching clause quote)
PROBES = {
    "h1_truthful": "only sincerely asserts things it believes to be true",
    "h2_calibrated": "acknowledges its own uncertainty or lack of knowledge when relevant",
    "h4_forthright": "proactively shares information helpful to the user",
    "h5_nondeceptive": "never tries to create false impressions of itself or the world in the user",
    "h7_antireliance": "fostering independent thinking over reliance on Claude",
    "g1_immediate": "The specific outcomes they want from this particular interaction",
    "g1_reliance": "The specific outcomes they want from this particular interaction",
    "g3_wellbeing": "long-term flourishing of the user and not just their immediate interests",
    "g5_nowishywashy": "wishy-washy response out of caution when it isn",
    "g6_autonomy": "right to make decisions about things within their own life and purview",
    "p1_opcomply": "seem restrictive or unusual, Claude should generally follow them as long as there is plausibly a legitimate business reason",
    # p1b/p4b are act-specialized instantiations of the SAME P1 sentence (c106),
    # not encodings of the defaults they collide with. They are the "operator
    # instruction" side of the p1b/p2 and p4b/p4 planted checks.
    "p1b_oplimits": "seem restrictive or unusual, Claude should generally follow them as long as there is plausibly a legitimate business reason",
    "p2_telllimits": "Always be willing to tell users what it cannot help with in the current operator context",
    "p3_noharmdeceive": "Never deceive users in ways that could cause real harm",
    "p4_emergency": "Always refer users to relevant emergency services",
    "p4b_opsilence": "seem restrictive or unusual, Claude should generally follow them as long as there is plausibly a legitimate business reason",
    "c317_autonomy": "respect the right of people to make their own choices and act within their own purview",
}


def load_clauses():
    return json.load(open(CLAUSES))["clauses"]


def norm_ids_in_rules(text):
    return [m.group(1) for m in re.finditer(r'^source\((\w+),', text, re.M)]


def resolve(clauses):
    """norm -> (status, payload). status in {ok, none, ambiguous}."""
    out = {}
    for nid, probe in PROBES.items():
        hits = [c for c in clauses if probe in c["quote"]]
        if len(hits) == 1:
            out[nid] = ("ok", hits[0])
        elif not hits:
            out[nid] = ("none", probe)
        else:
            out[nid] = ("ambiguous", hits)
    return out


def verify(resolved):
    """Independent re-check: probe must be an exact substring of the quote."""
    fails = []
    for nid, (status, payload) in resolved.items():
        if status != "ok":
            continue
        if PROBES[nid] not in payload["quote"]:
            fails.append((nid, payload["id"]))
    return fails


def render_facts(resolved):
    lines = []
    for nid in PROBES:
        status, payload = resolved[nid]
        if status != "ok":
            continue
        loc = payload["locator"].replace('"', "'")
        lines.append(f'locator({nid}, "{loc}", "{payload["id"]}", "{payload["kind"]}").')
    return lines


def write_rules(lines):
    text = open(RULES).read()
    block = ("\n% ---------- paragraph-level provenance (OUTPUT METADATA ONLY) ----------\n"
             "% locator(NormId, ParagraphLocator, ClauseId, ClauseKind).\n"
             "% Generated by backfill_locators.py; each clause verified to contain the\n"
             "% rule's source sentence as an exact substring. These facts are inert:\n"
             "% they appear in NO rule body or head and cannot affect derivation.\n"
             + "\n".join(lines) + "\n#show locator/4.\n")
    marker = "#show source/2.\n"
    assert marker in text
    # idempotent: strip any previously generated block
    text = re.sub(r"\n% -+ paragraph-level provenance.*?#show locator/4\.\n",
                  "", text, flags=re.S)
    text = text.replace(marker, marker + block, 1)
    open(RULES, "w").write(text)


def main():
    clauses = load_clauses()
    rules_text = open(RULES).read()
    ids = norm_ids_in_rules(rules_text)
    missing_probe = [n for n in ids if n not in PROBES]
    resolved = resolve(clauses)

    print(f"norms with source/2 in rules.lp: {len(ids)}; probes defined: {len(PROBES)}")
    if missing_probe:
        print(f"!! no probe defined for: {missing_probe}")

    ok = [n for n, (s, _) in resolved.items() if s == "ok"]
    for nid in PROBES:
        status, payload = resolved[nid]
        if status == "ok":
            print(f"  OK   {nid:18s} {payload['id']} [{payload['kind']:12s}] {payload['locator']}")
        elif status == "none":
            print(f"  MISS {nid:18s} zero clauses contain probe: {payload!r}")
        else:
            print(f"  AMBI {nid:18s} {len(payload)} clauses match: "
                  f"{[c['id'] for c in payload]}")

    fails = verify(resolved)
    print(f"\nverification: {len(ok)}/{len(PROBES)} resolved; "
          f"exact-substring check {'100% PASS' if not fails else 'FAILURES: %s' % fails}")

    if "--write" in sys.argv:
        write_rules(render_facts(resolved))
        print(f"wrote {len(ok)} locator/4 facts into rules.lp")


if __name__ == "__main__":
    main()
